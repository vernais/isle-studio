/* B-3：Markdown 残留清理
   模型（规划器 / Isle）偶尔会把 **加粗**、`代码`、# 标题 等标记写进提示词与回复，
   画布提示词和气泡都应显示纯文本。这里做保守清洗：只删强调类标记，
   不动列表短横线、括号等可能属于提示词内容本身的字符。 */
export function mdPlain(s) {
  return String(s ?? '')
    .replace(/```[a-zA-Z]*\n?/g, '')          // 代码块围栏
    .replace(/\*\*([^*]*)\*\*/g, '$1')        // **加粗**
    .replace(/(^|\s)__([^_]+)__(?=\s|$|[，。、；：！？）)】])/g, '$1$2')
    .replace(/`([^`]+)`/g, '$1')              // `代码`
    .replace(/^#{1,6}\s+/gm, '')              // 行首标题 #
    .replace(/\*/g, '')                        // 残余单星号（模型偶发）
    .replace(/[ \t]+\n/g, '\n')
    .trim()
}
